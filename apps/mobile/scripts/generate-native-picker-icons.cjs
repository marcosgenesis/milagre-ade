// Rasterize desktop's Hugeicons for SwiftUI menus without hosting React views in them.
// Run: node apps/mobile/scripts/generate-native-picker-icons.cjs
/* global __dirname, __filename */
const { Buffer } = require("node:buffer");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { GitForkIcon, LaptopIcon } = require("@hugeicons/core-free-icons");

async function generate() {
  const { app, BrowserWindow } = require("electron");
  await app.whenReady();
  const window = new BrowserWindow({ show: false });
  try {
    await window.loadURL("about:blank");
    const icons = { laptop: LaptopIcon, fork: GitForkIcon };
    const result = {};
    for (const [name, icon] of Object.entries(icons)) {
      result[name] = {};
      for (const scheme of ["light", "dark"]) {
        const color = scheme === "dark" ? "#a5a8ad" : "#62656b";
        const paths = icon
          .map(([tag, attributes]) => {
            const props = { ...attributes, strokeWidth: 1.8 };
            delete props.key;
            return `<${tag} ${Object.entries(props)
              .map(([key, value]) => `${key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}="${value}"`)
              .join(" ")}/>`;
          })
          .join("");
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72" viewBox="0 0 24 24" fill="none" color="${color}">${paths}</svg>`;
        result[name][scheme] = await window.webContents.executeJavaScript(`new Promise((resolve, reject) => {
          const image = new Image();
          image.onload = () => {
            const canvas = document.createElement('canvas');
            canvas.width = canvas.height = 72;
            canvas.getContext('2d').drawImage(image, 0, 0);
            resolve(canvas.toDataURL('image/png'));
          };
          image.onerror = reject;
          image.src = ${JSON.stringify("data:image/svg+xml;base64," + Buffer.from(svg).toString("base64"))};
        })`);
      }
    }
    fs.writeFileSync(
      path.join(__dirname, "../src/native-picker-icons.gen.ts"),
      `// Generated by apps/mobile/scripts/generate-native-picker-icons.cjs from the desktop icon set.\nexport const nativePickerIcons = ${JSON.stringify(result, null, 2)} as const;\n`,
    );
  } finally {
    window.destroy();
    app.quit();
  }
}

if (process.versions.electron)
  void generate().catch((error) => {
    console.error(error);
    process.exit(1);
  });
else {
  const env = { ...process.env };
  delete env.ELECTRON_RUN_AS_NODE;
  const result = spawnSync(require("electron"), [__filename], { env, stdio: "inherit" });
  process.exitCode = result.status ?? 1;
}
