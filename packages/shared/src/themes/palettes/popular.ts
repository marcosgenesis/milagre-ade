import { ansi, syntax } from "../build.ts";
import type { ThemeDefinition, ThemeId, ThemeSource } from "../types.ts";

type Spec = {
  page: string;
  surface: string;
  ink: string;
  ink2: string;
  ink3: string;
  accent: string;
  green: string;
  orange: string;
  red: string;
  purple: string;
  yellow: string;
  blue: string;
  cyan: string;
  /** Explicit extras where the theme publishes a matching color. */
  extra?: Partial<ThemeSource>;
};

/** Syntax per theme: plain = ink, comment = ink3, keyword = purple, string = green, number = orange, function = blue, type = yellow, tag = red, property = cyan. */
function source(s: Spec): ThemeSource {
  return {
    page: s.page,
    surface: s.surface,
    ink: s.ink,
    ink2: s.ink2,
    ink3: s.ink3,
    accent: s.accent,
    green: s.green,
    orange: s.orange,
    red: s.red,
    purple: s.purple,
    ansi: ansi({
      black: s.surface,
      red: s.red,
      green: s.green,
      yellow: s.yellow,
      blue: s.blue,
      magenta: s.purple,
      cyan: s.cyan,
      white: s.ink3,
      brightWhite: s.ink,
    }),
    syntax: syntax({
      plain: s.ink,
      comment: s.ink3,
      keyword: s.purple,
      string: s.green,
      number: s.orange,
      function: s.blue,
      type: s.yellow,
      tag: s.red,
      property: s.cyan,
    }),
    ...s.extra,
  };
}

const theme = (id: ThemeId, name: string, lightName: string, darkName: string, light: Spec, dark: Spec): ThemeDefinition => ({
  id,
  name,
  group: "Popular",
  lightName,
  darkName,
  light: source(light),
  dark: source(dark),
});

